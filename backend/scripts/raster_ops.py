    if not np.isfinite(arr).any():
        raise OpError("No elevation data inside this area.")
    return {"source": "Copernicus DEM GLO-30", "tiles": len(sources), "width": out.RasterXSize,
            "height": out.RasterYSize, "stats": stats_of(arr)}


