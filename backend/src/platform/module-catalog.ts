/** A tool switched off takes its features with it. */
export function expandSwitchedOff(ids: string[]): string[] {
  const out = new Set(ids);
  for (const t of SWITCHABLE_TOOLS) if (out.has(t.id)) for (const c of t.children ?? []) out.add(c.id);
  return [...out];
}
