/**
 * Lets Keycloak sign-in work when the app is opened over plain HTTP on a
 * LAN address (e.g. http://192.168.20.53:4200 for a demo).
 *
 * Browsers only expose `crypto.randomUUID()` and `crypto.subtle` in a
 * "secure context" (HTTPS or localhost). keycloak-js needs both — a random
 * state id and a SHA-256 hash for the PKCE code challenge — so on a LAN IP
 * sign-in failed with "Web Crypto API is not available". This fills in
 * exactly those two pieces, ONLY when the page is not a secure context;
 * on localhost / HTTPS nothing here runs and the browser's own
 * implementations are used.
 *
 * The randomness still comes from `crypto.getRandomValues()`, which
 * browsers provide in insecure contexts too; SHA-256 is a plain
 * implementation of FIPS 180-4 (the hash input is public anyway — PKCE
 * protects the code exchange, not the hash). Production should be served
 * over HTTPS, where this file is a no-op.
 */

